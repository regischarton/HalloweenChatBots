#!/usr/bin/env python3
"""
Bakes the app (HTML + content + every image) into the docs/ folder, ready for GitHub Pages:
    docs/index.html            the whole app in one file
    docs/sw.js                 offline support (saves the app on the iPad)
    docs/manifest.webmanifest  home-screen app settings
    docs/*.png                 home-screen icons

Usage (from this folder):   python build.py      (or  py build.py  on Windows)
"""
import base64, hashlib, json, re, shutil, sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent
APP = ROOT / "app"
IMAGES = APP / "images"
ICONS = APP / "icons"
OUT_DIR = ROOT / "docs"
MIME = {".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg",
        ".gif": "image/gif", ".webp": "image/webp", ".svg": "image/svg+xml"}
MARKER = '<script src="content.js"></script>'
BIG = 3 * 1024 * 1024

MANIFEST = {
    "name": "Halloween Chat",
    "short_name": "Boo Chat",
    "start_url": "./",
    "scope": "./",
    "display": "fullscreen",
    "orientation": "any",
    "background_color": "#212121",
    "theme_color": "#212121",
    "icons": [
        {"src": "apple-touch-icon.png", "sizes": "180x180", "type": "image/png"},
        {"src": "icon-512.png", "sizes": "512x512", "type": "image/png"},
    ],
}

SW = """// Generated by build.py - do not edit. Version changes whenever the app changes.
const CACHE = "halloween-chat-__VERSION__";
const FILES = ["./", "./index.html", "./manifest.webmanifest", "./apple-touch-icon.png", "./icon-512.png"];

self.addEventListener("install", (e) => {
  // cache: "reload" skips the browser's HTTP cache so we never save a stale copy as the new version
  e.waitUntil(
    caches.open(CACHE)
      .then((c) => c.addAll(FILES.map((f) => new Request(f, { cache: "reload" }))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("halloween-chat-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Cache first: the app always opens from the iPad's saved copy, even with no Wi-Fi.
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) =>
      hit || fetch(e.request).catch(() => caches.match("./index.html"))
    )
  );
});
"""


def data_uri(p: Path) -> str:
    if p.stat().st_size > BIG:
        print(f"  ! {p.name} is {p.stat().st_size // 1024} KB - consider resizing to ~1600px to keep the iPad snappy")
    return f"data:{MIME[p.suffix.lower()]};base64,{base64.b64encode(p.read_bytes()).decode('ascii')}"


def strip_comments(js: str):
    """Remove // and /* */ comments (but not text inside strings).
    Returns (code_without_comments, text_of_all_comments)."""
    out, comments, i, n = [], [], 0, len(js)
    while i < n:
        c = js[i]
        if c in "\"'`":                      # string: copy through, honouring escapes
            j = i + 1
            while j < n and js[j] != c:
                j += 2 if js[j] == "\\" else 1
            out.append(js[i:j + 1]); i = j + 1
        elif js.startswith("//", i):          # line comment
            j = js.find("\n", i); j = n if j < 0 else j
            comments.append(js[i:j]); i = j
        elif js.startswith("/*", i):          # block comment (keep its line breaks)
            j = js.find("*/", i + 2); j = n if j < 0 else j + 2
            comments.append(js[i:j]); out.append("\n" * js.count("\n", i, j)); i = j
        else:
            out.append(c); i += 1
    return "".join(out), "\n".join(comments)


def main() -> int:
    html = (APP / "index.html").read_text(encoding="utf-8")
    content = (APP / "content.js").read_text(encoding="utf-8")
    if MARKER not in html:
        print("ERROR: could not find the content.js script tag in app/index.html")
        return 1

    # Commented-out lines are ignored. Images mentioned only in comments are "parked":
    # not embedded, and not picked up as extras either.
    content, commented = strip_comments(content)
    parked = {(APP / rel).resolve() for rel in re.findall(r'images/[^"\'`\s,}]+', commented)}

    used, missing = set(), []

    def inline(m):
        quote, rel = m.group(1), m.group(2)
        p = APP / rel
        if not p.is_file() or p.suffix.lower() not in MIME:
            missing.append(rel)
            return m.group(0)
        used.add(p.resolve())
        return quote + data_uri(p) + quote

    content = re.sub(r'(["\'`])(images/[^"\'`]+)\1', inline, content)

    parked = {p for p in parked if p.is_file()} - used   # listed for real somewhere else wins
    auto = []
    if IMAGES.is_dir():
        for p in sorted(IMAGES.iterdir()):   # subfolders of app/images/ are ignored
            if p.is_file() and p.suffix.lower() in MIME and p.resolve() not in used and p.resolve() not in parked:
                auto.append({"src": data_uri(p), "name": p.name})

    build = datetime.now().strftime("%Y-%m-%d %H:%M")
    script = ("<script>\n" + content.replace("</script", "<\\/script") +
              "\nwindow.HALLOWEEN_AUTO_IMAGES = " + json.dumps(auto) + ";" +
              "\nwindow.APP_BUILD = " + json.dumps(build) + ";\n</script>")
    page = html.replace(MARKER, script)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "index.html").write_text(page, encoding="utf-8")
    (OUT_DIR / "manifest.webmanifest").write_text(json.dumps(MANIFEST, indent=2), encoding="utf-8")
    for icon in ("apple-touch-icon.png", "icon-512.png"):
        shutil.copyfile(ICONS / icon, OUT_DIR / icon)
    version = hashlib.sha256(page.encode("utf-8")).hexdigest()[:12]
    (OUT_DIR / "sw.js").write_text(SW.replace("__VERSION__", version), encoding="utf-8")
    (OUT_DIR / ".nojekyll").write_text("", encoding="utf-8")

    size = (OUT_DIR / "index.html").stat().st_size // 1024
    print(f"Built docs/  (index.html {size} KB, version {build} / {version})")
    print(f"  {len(used)} listed images")
    if parked:
        print(f"  {len(parked)} commented-out (skipped): " + ", ".join(sorted(p.name for p in parked)))
    if auto:
        print(f"  {len(auto)} unlisted images picked up with random prompts: " + ", ".join(a["name"] for a in auto))
    for m in missing:
        print(f"  ! WARNING: content.js refers to '{m}' but that file isn't in app/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
